import assert from 'node:assert/strict';
import {CATALOGUE} from '../catalogue.mjs';
import {checkCatalogueParity} from '../catalogue-parity.mjs';
let n=0;const check=(v,msg)=>{assert.ok(v,msg);n++};
const src=CATALOGUE.map(p=>({...p}));
let p=checkCatalogueParity(src,CATALOGUE);
check(p.exactlyMatched&&p.sourceCount===20&&p.matchedCount===20,'identical versioned 20-item catalogue matches');
let changed=structuredClone(src);changed[0].listPrice++;
p=checkCatalogueParity(changed,CATALOGUE);
check(!p.exactlyMatched&&p.changedCodes.length===1&&p.changedCodes[0]===src[0].code,'server flags one changed price');
changed=structuredClone(src);changed[1].name+=' TEST';
check(checkCatalogueParity(changed,CATALOGUE).changedCodes.length===1,'server flags changed product name');
changed=structuredClone(src).slice(1);
check(checkCatalogueParity(changed,CATALOGUE).extraCodes.includes(src[0].code),'server flags unsynced local product');
changed=structuredClone(src);changed.push({...src[0],code:'TP-99999'});
check(checkCatalogueParity(changed,CATALOGUE).missingCodes.includes('TP-99999'),'server flags source-only product');
changed=structuredClone(src);changed[1].code=src[0].code;
assert.throws(()=>checkCatalogueParity(changed,CATALOGUE),/INVALID_CATALOGUE_CODE/);n++;
changed=structuredClone(src);delete changed[0].unit;
assert.throws(()=>checkCatalogueParity(changed,CATALOGUE),/INVALID_CATALOGUE_FIELD/);n++;
changed=structuredClone(src);changed[0].listPrice=-1;
assert.throws(()=>checkCatalogueParity(changed,CATALOGUE),/INVALID_CATALOGUE_PRICE/);n++;
check(Object.keys(checkCatalogueParity(src,CATALOGUE)).every(k=>!/(customer|phone|email|address)/i.test(k)),'no identifying customer data in parity report');
console.log('PASS '+n+'/'+n+' versioned catalogue parity / diverged-price safety tests');
