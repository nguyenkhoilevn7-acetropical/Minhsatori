import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.dirname(here),temp=mkdtempSync(path.join(tmpdir(),'satori-customer-links-'));
const admin='ADMIN_TEST_ONLY_0123456789_ABCDEFGHIJKLMNOPQRSTUVWXYZ+/=';
const port=30500+Math.floor(Math.random()*1000),origin='http://127.0.0.1:'+port;
const proc=spawn(process.execPath,[path.join(root,'server.mjs')],{env:{...process.env,PORT:String(port),DEMO_BIND:'127.0.0.1',DEMO_DATA_DIR:temp,CUSTOMER_LINKS_ADMIN_TOKEN:admin+' \n',GEMINI_API_KEY:''},stdio:'ignore'});
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const req=async(p,method='GET',data,auth)=>{const res=await fetch(origin+p,{method,headers:{...(data?{'content-type':'application/json'}:{}),...(auth?{authorization:'Bearer '+auth}:{})},body:data?JSON.stringify(data):undefined});const raw=await res.arrayBuffer();let json;try{json=JSON.parse(Buffer.from(raw).toString('utf8'))}catch{}return {status:res.status,data:json,bytes:Buffer.from(raw)}};
let tests=0;const ok=(cond,message)=>{assert.ok(cond,message);tests++};
try{
 let live=false;for(let i=0;i<100;i++){try{const h=await req('/health');if(h.status===200){live=true;break}}catch{}await wait(90)}
 ok(live,'sandbox started');
 let denied=await req('/api/admin/customers');ok(denied.status===401,'anonymous admin denied');
 const adminCheck=await req('/api/admin/status','GET',undefined,admin);ok(adminCheck.status===200&&adminCheck.data.ok,'base64 admin token survives pasted env whitespace');
 denied=await req('/api/admin/customers','POST',{name:'Fake Customer'});ok(denied.status===401,'anonymous create denied');
 const creation=await req('/api/admin/customers','POST',{name:'Khách Giả C',phone:'000 000 0003',address:'789 Đường Giả Lập, TP.HCM',discount:25,ship:8},admin);
 ok(creation.status===201&&creation.data.ok,'admin can create sandbox customer');
 const url=new URL(creation.data.customerLink),token=decodeURIComponent(url.pathname.split('/').at(-1));
 ok(token.length>=40&&!url.searchParams.has('phone'),'unguessable link contains no phone');
 const saved=readFileSync(path.join(temp,'customer-links-SANDBOX.json'),'utf8');
 ok(!saved.includes(token),'only hash stored in registry');
 const session=await req('/api/session?token='+encodeURIComponent(token));
 ok(session.data.profile.name==='Khách Giả C'&&session.data.profile.discount===25,'assigned discount and name from server');
 const empty=await req('/api/history?token='+encodeURIComponent(token));
 ok(empty.status===200&&empty.data.orders.length===0,'new customer has empty history');
 const message=await req('/api/message','POST',{token,message:'Cho tôi 10 thùng Satori 500ml'});
 ok(message.status===200&&message.data.quote?.discount===25,'private quote uses assigned discount');
 const confirm=await req('/api/confirm','POST',{token,quoteId:message.data.quote.quoteId,requestId:'customer-c-test-123',deliveryNote:'Giao sau 3 giờ, gọi trước khi đến'});
 ok(confirm.status===200&&confirm.data.order?.ref,'created sandbox invoice');
 const history=await req('/api/history?token='+encodeURIComponent(token));
 ok(history.data.count===1&&history.data.orders[0].ref===confirm.data.order.ref,'history includes only own invoice');
 ok(history.data.orders[0].deliveryNote==='Giao sau 3 giờ, gọi trước khi đến','notes visible in own history');
 ok(!Number.isNaN(Date.parse(history.data.orders[0].createdAt)),'history includes exact order timestamp');
 const other=await req('/api/history?token=demo-a');
 ok(other.status===200&&other.data.count===0,'customer A cannot see customer C history');
 const cross=await req('/api/invoice/'+confirm.data.order.ref+'?token=demo-a');
 ok(cross.status===404,'other customer cannot download invoice PDF');
 const own=await req('/api/invoice/'+confirm.data.order.ref+'?token='+encodeURIComponent(token));
 ok(own.status===200&&own.bytes.subarray(0,4).toString()==='%PDF','owner can download invoice PDF');
 const id=creation.data.customer.id;
 const rotated=await req('/api/admin/customers/'+id+'/rotate','POST',{},admin);
 ok(rotated.status===200,'rotate link works');
 const newToken=new URL(rotated.data.customerLink).pathname.split('/').at(-1);
 const old=await req('/api/session?token='+encodeURIComponent(token));
 ok(old.status===404,'rotated-out link is refused');
 const still=await req('/api/history?token='+encodeURIComponent(newToken));
 ok(still.data.count===1,'history follows customer ID after rotation');
 const revoke=await req('/api/admin/customers/'+id+'/revoke','POST',{},admin);
 const blocked=await req('/api/history?token='+encodeURIComponent(newToken));
 ok(revoke.status===200&&blocked.status===404,'revoke blocks previously active link');
 console.log('Customer link tests PASS '+tests+'/'+tests);
}finally{proc.kill();rmSync(temp,{recursive:true,force:true})}
