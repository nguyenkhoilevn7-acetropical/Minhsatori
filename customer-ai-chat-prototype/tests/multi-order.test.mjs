import assert from 'node:assert/strict';
import {parseMultiOrder} from '../multi-order.mjs';
const a={favourite:'S5L',uniqueFavourite:true},b={favourite:'S500',uniqueFavourite:false};
let checks=0;const check=(ok,msg)=>{assert.ok(ok,msg);checks++};
let p=parseMultiOrder('Cho 10 thùng Satori 500ml và 5 thùng Hikari 500ml',b);
check(p?.items?.length===2,'two products recognised');
check(p.items[0].qty===10&&p.items[1].qty===5,'two distinct quantities');
check(p.items[0].sku==='S500'&&p.items[1].sku==='TP-00081','Satori and Hikari SKUs recognised');
p=parseMultiOrder('Cho 10 thùng Satori 500ml, 5 thùng Hikari 500ml, giao sau 2 giờ chiều, nhớ gọi trước khi giao',b);
check(p?.items?.length===2,'delivery time not treated as another quantity');
p=parseMultiOrder('Cho 10 thùng 5L có vòi và 3 thùng 500ml',a);
check(p?.items?.length===2,'5L and 500ml separately');
p=parseMultiOrder('Cho 10 thùng Hikari 500ml và 3 thùng nước ép mãng cầu',a);
check(p?.items?.length===2,'Hikari and juice recognised');
p=parseMultiOrder('Cho mười thùng Satori 500ml và năm thùng Hikari 500ml',b);
check(p?.items?.[0].qty===10&&p?.items?.[1].qty===5,'Vietnamese number words recognised');
p=parseMultiOrder('Cho 10 thùng Satori 500ml và 3 thùng Satori 500ml',b);
check(p?.needMoreDetails,'repeated SKU not double charged');
p=parseMultiOrder('Cho 10 thùng Satori 500ml và 3 thùng trà sữa',b);
check(p?.needMoreDetails&&!p?.items,'unsupported second item blocks partial quote');
p=parseMultiOrder('Cho 10 thùng Satori 500ml và 3 thùng 5L',b);
check(p?.needMoreDetails&&!p?.items,'unclear 5L variant blocks partial quote');
p=parseMultiOrder('Cho 10 thùng Satori 500ml và 3 bình Hikari 500ml',b);
check(p?.needMoreDetails,'unit mismatch blocked');
p=parseMultiOrder('Cho 300 thùng Satori 500ml và 250 thùng Hikari 500ml',b);
check(p?.needMoreDetails,'max quantity enforced across lines');
p=parseMultiOrder('Cho tôi 10 thùng Satori 500ml',b);
check(p===null,'single product uses legacy parser');
console.log('PASS '+checks+'/'+checks+' safe multi-item extraction checks');
